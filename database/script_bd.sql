CREATE OR REPLACE PROCEDURE SP_BUSCAR_PRODUCTOS(
    P_CLAVE IN VARCHAR2,
    P_TIPO_PRODUCTO_ID IN NUMBER,
    P_CURSOR OUT SYS_REFCURSOR
)
AS
BEGIN
OPEN P_CURSOR FOR
SELECT
    P.PRODUCTO_ID,
    P.CLAVE,
    P.NOMBRE,
    P.PRECIO,
    P.TIPO_PRODUCTO_ID,
    TP.NOMBRE AS TIPO_PRODUCTO,
    P.ACTIVO
FROM PRODUCTO P
         INNER JOIN TIPO_PRODUCTO TP
                    ON P.TIPO_PRODUCTO_ID = TP.TIPO_PRODUCTO_ID
WHERE
    (P_CLAVE IS NULL OR UPPER(P.CLAVE) LIKE '%' || UPPER(P_CLAVE) || '%')
  AND
    (P_TIPO_PRODUCTO_ID IS NULL OR P.TIPO_PRODUCTO_ID = P_TIPO_PRODUCTO_ID)
ORDER BY P.PRODUCTO_ID;
END;
/

CREATE OR REPLACE PROCEDURE SP_GUARDAR_PRODUCTO(
    P_CLAVE IN VARCHAR2,
    P_NOMBRE IN VARCHAR2,
    P_PRECIO IN NUMBER,
    P_TIPO_PRODUCTO_ID IN NUMBER,
    P_ACTIVO IN NUMBER
)
AS
BEGIN
INSERT INTO PRODUCTO(CLAVE, NOMBRE, PRECIO, TIPO_PRODUCTO_ID, ACTIVO)
VALUES(P_CLAVE, P_NOMBRE, P_PRECIO, P_TIPO_PRODUCTO_ID, P_ACTIVO);

COMMIT;
END;
/

CREATE OR REPLACE PROCEDURE SP_ACTUALIZAR_PRODUCTO(
    P_PRODUCTO_ID IN NUMBER,
    P_CLAVE IN VARCHAR2,
    P_NOMBRE IN VARCHAR2,
    P_PRECIO IN NUMBER,
    P_TIPO_PRODUCTO_ID IN NUMBER,
    P_ACTIVO IN NUMBER
)
AS
BEGIN
UPDATE PRODUCTO
SET
    CLAVE = P_CLAVE,
    NOMBRE = P_NOMBRE,
    PRECIO = P_PRECIO,
    TIPO_PRODUCTO_ID = P_TIPO_PRODUCTO_ID,
    ACTIVO = P_ACTIVO
WHERE PRODUCTO_ID = P_PRODUCTO_ID;

COMMIT;
END;
/

CREATE OR REPLACE PROCEDURE SP_ELIMINAR_PRODUCTO(
    P_PRODUCTO_ID IN NUMBER
)
AS
BEGIN
DELETE FROM PRODUCTO_PROVEEDOR
WHERE PRODUCTO_ID = P_PRODUCTO_ID;

DELETE FROM PRODUCTO
WHERE PRODUCTO_ID = P_PRODUCTO_ID;

COMMIT;
END;
