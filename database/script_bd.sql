CREATE TABLE TIPO_PRODUCTO (
TIPO_PRODUCTO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(100) NOT NULL,
DESCRIPCION VARCHAR2(200)
);


CREATE TABLE PROVEEDOR (
PROVEEDOR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
NOMBRE VARCHAR2(100) NOT NULL,
DESCRIPCION VARCHAR2(200)
);


CREATE TABLE PRODUCTO (
PRODUCTO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
CLAVE VARCHAR2(50) NOT NULL,
NOMBRE VARCHAR2(100) NOT NULL,
PRECIO NUMBER(10,2) NOT NULL,
TIPO_PRODUCTO_ID NUMBER NOT NULL,
ACTIVO NUMBER DEFAULT 1,

CONSTRAINT FK_PRODUCTO_TIPO FOREIGN KEY (TIPO_PRODUCTO_ID)
REFERENCES TIPO_PRODUCTO(TIPO_PRODUCTO_ID)
);


CREATE TABLE PRODUCTO_PROVEEDOR (
PRODUCTO_PROVEEDOR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
PRODUCTO_ID NUMBER NOT NULL,
PROVEEDOR_ID NUMBER NOT NULL,
CLAVE_PROVEEDOR VARCHAR2(50) NOT NULL,
COSTO NUMBER(10,2) NOT NULL,

CONSTRAINT FK_PP_PRODUCTO FOREIGN KEY (PRODUCTO_ID)
REFERENCES PRODUCTO(PRODUCTO_ID),

CONSTRAINT FK_PP_PROVEEDOR FOREIGN KEY (PROVEEDOR_ID)
REFERENCES PROVEEDOR(PROVEEDOR_ID)
);


